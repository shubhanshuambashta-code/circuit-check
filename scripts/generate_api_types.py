"""Generate dependency-free TS contracts from FastAPI's actual OpenAPI schema."""
import argparse
import json
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from backend.main import app

def ts(schema):
    if '$ref' in schema:return schema['$ref'].split('/')[-1]
    if 'enum' in schema:return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'const' in schema:return json.dumps(schema['const'])
    for combination,separator in [('anyOf',' | '),('oneOf',' | '),('allOf',' & ')]:
        if combination in schema:return '('+separator.join(ts(s) for s in schema[combination])+')'
    kind=schema.get('type')
    if kind=='array':return '('+ts(schema.get('items',{}))+')[]'
    if kind in ('integer','number'):return 'number'
    if kind in ('string','boolean','null'):return kind
    if kind=='object' or 'properties' in schema:
        required=schema.get('required',[])
        fields=[json.dumps(key)+('' if key in required else '?')+': '+ts(value)+';' for key,value in schema.get('properties',{}).items()]
        additional=schema.get('additionalProperties')
        if additional is True or not fields and additional is not False:fields.append('[key: string]: '+(ts(additional) if isinstance(additional,dict) else 'unknown')+';')
        return '{ '+' '.join(fields)+' }'
    return 'unknown'

def generate():
    schema=app.openapi()
    body='// Generated by scripts/generate_api_types.py. Do not edit by hand.\n'
    for name,value in sorted(schema.get('components',{}).get('schemas',{}).items()):body+='export type '+name+' = '+ts(value)+';\n'
    paths={}
    for path,operations in schema['paths'].items():
        methods={}
        for method,operation in operations.items():
            if method not in ('get','post','put','patch','delete'):continue
            response=next((v for k,v in operation.get('responses',{}).items() if k.startswith('2')),{}).get('content',{}).get('application/json',{}).get('schema',{})
            methods[method]=ts(response)
        paths[path]=methods
    body+='export type ApiResponses = {\n'+''.join('  '+json.dumps(path)+': { '+''.join(json.dumps(method)+': '+value+'; ' for method,value in methods.items())+'};\n' for path,methods in sorted(paths.items()))+'};\n'
    return {ROOT/'docs/openapi.json':json.dumps(schema,indent=2,sort_keys=True)+'\n',ROOT/'src/api.generated.ts':body}

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,content in generate().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8')!=content:raise SystemExit(f'Generated API contract is stale: {path.name}. Run python scripts/generate_api_types.py.')
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content,encoding='utf-8')
